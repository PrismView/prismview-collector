-- 백필 중 OKX가 2026-07-31 봉까지 제공함을 확인 (3개월보다 김)
-- → 8월 이전 파티션 추가. 7월만으로 모자랄 경우를 대비해 6월도 함께.
-- DEFAULT 파티션은 여전히 만들지 않는다: 더 오래된 봉이 오면 다시 에러로 드러나게.
CREATE TABLE candle_1s_2026_06 PARTITION OF candle_1s FOR VALUES
    FROM ((EXTRACT(EPOCH FROM TIMESTAMPTZ '2026-06-01 00:00:00+00') * 1000)::BIGINT)
    TO   ((EXTRACT(EPOCH FROM TIMESTAMPTZ '2026-07-01 00:00:00+00') * 1000)::BIGINT);

CREATE TABLE candle_1s_2026_07 PARTITION OF candle_1s FOR VALUES
    FROM ((EXTRACT(EPOCH FROM TIMESTAMPTZ '2026-07-01 00:00:00+00') * 1000)::BIGINT)
    TO   ((EXTRACT(EPOCH FROM TIMESTAMPTZ '2026-08-01 00:00:00+00') * 1000)::BIGINT);